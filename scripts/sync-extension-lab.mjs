import fs from "node:fs";
import path from "node:path";

const repoRoot = process.cwd();
const extensionRoot = path.join(repoRoot, "extensions", "aoe2-aiscript-cursor-local-lab");
const labRoot = path.join(extensionRoot, "lab");

const copyEntries = [
  ["src", "src"],
  [path.join("docs", "extracted", "inventories"), path.join("docs", "extracted", "inventories")],
  [path.join("docs", "reference", "generated"), path.join("docs", "reference", "generated")],
  [path.join("docs", "workflows", "validator-diagnostic-codes.json"), path.join("docs", "workflows", "validator-diagnostic-codes.json")],
];

function copyRecursive(source, destination) {
  const stat = fs.statSync(source);
  if (stat.isDirectory()) {
    fs.mkdirSync(destination, { recursive: true });
    for (const entry of fs.readdirSync(source)) {
      copyRecursive(path.join(source, entry), path.join(destination, entry));
    }
    return;
  }
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.copyFileSync(source, destination);
}

function assertExists(source) {
  if (!fs.existsSync(source)) {
    throw new Error(`required extension lab source does not exist: ${source}`);
  }
}

fs.rmSync(labRoot, { recursive: true, force: true });
for (const [sourceRelative, destinationRelative] of copyEntries) {
  const source = path.join(repoRoot, sourceRelative);
  const destination = path.join(labRoot, destinationRelative);
  assertExists(source);
  copyRecursive(source, destination);
}

fs.writeFileSync(
  path.join(labRoot, "README.md"),
  [
    "# Bundled AOE2 AI Parser Runtime",
    "",
    "Generated by `node scripts/sync-extension-lab.mjs` before packaging.",
    "Do not edit this copy directly; edit the repo source and regenerate.",
    "",
  ].join("\n"),
  "utf8",
);

console.log(`Synced bundled extension lab runtime to ${path.relative(repoRoot, labRoot)}`);
